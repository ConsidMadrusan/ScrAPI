import "server-only";

import { codegen } from "@graphql-codegen/core";
import * as typescriptGenericSdk from "@graphql-codegen/typescript-generic-sdk";
import * as typescriptOperations from "@graphql-codegen/typescript-operations";
import { isEnumType, isScalarType, parse, print, printSchema, specifiedScalarTypes, type DocumentNode, type GraphQLSchema } from "graphql";
import { isSafeArchivePath } from "@/lib/archive/safe-path";
import { resolveTarget, toDestinationPath, type TargetConfig } from "@/lib/targets/config";
import { formatMegabytes, MAX_CONCURRENT_GRAPHQL_GENERATIONS, MAX_OUTPUT_BYTES, utf8ByteLength } from "@/lib/validation/limits";
import type { Problem } from "@/lib/validation/problems";
import type { GraphqlGenerateRequest } from "@/lib/validation/requests";
import type { GeneratedFile, GraphqlGenerateSuccess } from "@/lib/validation/responses";
import { buildOperations, OperationBuildError } from "./build-operations";
import { csharpProjectFile, graphqlConfigFile, SCHEMA_EXTENSIONS } from "./csharp-project";
import { listGraphqlOperations, resolveGraphqlSelection } from "./operations";
import { parseGraphqlSchema } from "./parse";

export type GraphqlGenerateResult =
  | { ok: true; value: GraphqlGenerateSuccess }
  | { ok: false; status: number; errors: Problem[] };

/** Process-wide resource counter (not request state): GraphQL generations in progress. */
let runningGenerations = 0;

/** File names inside the client folder. */
export const TYPESCRIPT_CLIENT_FILE = "graphql.ts";
export const OPERATIONS_FILE_TS = "operations.graphql";
export const OPERATIONS_FILE_CSHARP = "Operations.graphql";

/**
 * Generates the GraphQL client for one framework combination. The schema is
 * parsed and the selection checked again (client checks are never trusted),
 * the operations are built, and then:
 *
 * - TypeScript targets: GraphQL Code Generator runs in this process with a
 *   fixed configuration, producing typed operations and an SDK with one method
 *   per operation (`getSdk(requester)`), independent of the HTTP client.
 * - C#: the files of a StrawberryShake client project are written; the C#
 *   code is generated by the user's own `dotnet build`.
 *
 * At most MAX_CONCURRENT_GRAPHQL_GENERATIONS run at once.
 */
export async function generateGraphqlClient(request: GraphqlGenerateRequest): Promise<GraphqlGenerateResult> {
  if (runningGenerations >= MAX_CONCURRENT_GRAPHQL_GENERATIONS) {
    return failure(503, "generator-busy", "The server is busy generating other clients. Try again in a moment.");
  }
  runningGenerations += 1;
  try {
    return await generate(request);
  } finally {
    runningGenerations -= 1;
  }
}

async function generate(request: GraphqlGenerateRequest): Promise<GraphqlGenerateResult> {
  const parsed = parseGraphqlSchema(request.schema);
  if (!parsed.ok) return { ok: false, status: 422, errors: parsed.errors };
  const schema = parsed.value;

  const selection = resolveGraphqlSelection(listGraphqlOperations(schema), request.selection);
  if (!selection.ok) {
    return selection.reason === "empty"
      ? failure(422, "empty-selection", "Select at least one operation.")
      : failure(
          422,
          "unknown-operations",
          `These operations are not in the schema: ${listSome(selection.unknownIds)}. The schema may have changed since you selected them. Go back and select the operations again.`,
        );
  }

  let document: DocumentNode;
  try {
    document = buildOperations(schema, selection.selected);
  } catch (error) {
    if (!(error instanceof OperationBuildError)) throw error;
    return failure(422, "operation-build-failed", `ScrAPI could not build the operations for this schema: ${error.message}`);
  }

  const target = resolveTarget(request.options);
  const contents =
    request.options.target === "csharp"
      ? csharpFiles(schema, document, target)
      : await typescriptFiles(schema, document);

  const files: GeneratedFile[] = Object.entries(contents).map(([relative, content]) => {
    const archivePath = `${target.archiveRoot}/${relative}`;
    return { archivePath, destinationPath: toDestinationPath(target, archivePath), content };
  });
  if (!files.every((file) => isSafeArchivePath(file.archivePath))) {
    throw new Error("Generated an unsafe archive path.");
  }
  const totalBytes = files.reduce((sum, file) => sum + utf8ByteLength(file.content), 0);
  if (totalBytes > MAX_OUTPUT_BYTES) {
    return failure(
      422,
      "output-too-large",
      `The generated code is larger than ${formatMegabytes(MAX_OUTPUT_BYTES)}. Select fewer operations and try again.`,
    );
  }

  return {
    ok: true,
    value: {
      ok: true,
      kind: "graphql",
      options: request.options,
      archiveRoot: target.archiveRoot,
      destinationRoot: target.destinationRoot,
      operations: selection.selected,
      files: files.sort((a, b) => (a.archivePath < b.archivePath ? -1 : 1)),
    },
  };
}

/** Typed operations and SDK, verified with @graphql-codegen 6.x (see CLAUDE.md, "GraphQL targets"). */
async function typescriptFiles(schema: GraphQLSchema, document: DocumentNode): Promise<Record<string, string>> {
  const output = await codegen({
    schema: parse(printSchema(schema)),
    schemaAst: schema,
    filename: TYPESCRIPT_CLIENT_FILE,
    documents: [{ location: OPERATIONS_FILE_TS, document }],
    config: {
      // Custom scalars carry no type information in the schema: `unknown` until the user narrows them.
      scalars: Object.fromEntries(customScalarNames(schema).map((name) => [name, "unknown"])),
      strictScalars: true,
      useTypeImports: true,
      // Plain DocumentNode constants: the requester sends them with `print()` from `graphql`.
      documentMode: "documentNode",
      dedupeOperationSuffix: true,
    },
    // typescript-operations 6.x emits the enums and input types the operations use;
    // adding the `typescript` plugin would declare them twice.
    plugins: [{ "typescript-operations": {} }, { "typescript-generic-sdk": {} }],
    pluginMap: { "typescript-operations": typescriptOperations, "typescript-generic-sdk": typescriptGenericSdk },
  });
  return { [TYPESCRIPT_CLIENT_FILE]: output, [OPERATIONS_FILE_TS]: print(document) };
}

function csharpFiles(schema: GraphQLSchema, document: DocumentNode, target: TargetConfig): Record<string, string> {
  const namespace = target.archiveRoot;
  return {
    [`${namespace}.csproj`]: csharpProjectFile(namespace),
    ".graphqlrc.json": graphqlConfigFile(namespace),
    "schema.graphql": `${printSchema(schema)}\n`,
    "schema.extensions.graphql": SCHEMA_EXTENSIONS,
    [OPERATIONS_FILE_CSHARP]: `${print(document)}\n`,
  };
}

function customScalarNames(schema: GraphQLSchema): string[] {
  const builtIn = new Set(specifiedScalarTypes.map((type) => type.name));
  return Object.values(schema.getTypeMap())
    .filter((type) => isScalarType(type) && !isEnumType(type) && !builtIn.has(type.name) && !type.name.startsWith("__"))
    .map((type) => type.name);
}

function listSome(ids: readonly string[]): string {
  const shown = ids.slice(0, 10).join(", ");
  return ids.length > 10 ? `${shown}, and ${String(ids.length - 10)} more` : shown;
}

function failure(status: number, code: string, message: string): Extract<GraphqlGenerateResult, { ok: false }> {
  return { ok: false, status, errors: [{ code, message }] };
}
