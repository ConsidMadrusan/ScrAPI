import type { GenerateSuccess } from "@/lib/validation/responses";
import { renderTree } from "./tree";
import type { Guide, GuideBlock } from "./types";

/** Name of the Markdown guide at the root of the ZIP. */
export const GUIDE_FILE_NAME = "INTEGRATION.md";

/**
 * Renders the guide as Markdown for INTEGRATION.md in the ZIP. It contains the
 * same steps as the guide on the page; file contents are in the ZIP itself.
 */
export function renderGuideMarkdown(guide: Guide, result: GenerateSuccess): string {
  const lines = [`# ${guide.title}`, "", "Generated by ScrAPI.", ""];

  if (guide.placeholders.length > 0) {
    lines.push("Values you must supply:", "");
    for (const placeholder of guide.placeholders) {
      lines.push(`- \`${placeholder.token}\`: ${placeholder.description}`);
    }
    lines.push("");
  }

  guide.steps.forEach((step, index) => {
    lines.push(`## Step ${String(index + 1)}: ${step.title}`, "");
    for (const block of step.blocks) lines.push(...renderBlock(block, result), "");
  });

  return `${lines.join("\n").trimEnd()}\n`;
}

function renderBlock(block: GuideBlock, result: GenerateSuccess): string[] {
  switch (block.kind) {
    case "text":
      return [block.text];
    case "list":
      return block.items.map((item) => `- ${item}`);
    case "command":
      return ["```sh", block.command, "```"];
    case "code":
      return [
        `${block.action === "create" ? "New file" : "Edit"} \`${block.file}\`:`,
        "",
        `\`\`\`${block.language}`,
        block.code.trimEnd(),
        "```",
      ];
    case "tree":
      return [
        "```text",
        renderTree(result.destinationRoot, result.files.map((file) => file.destinationPath)),
        "```",
      ];
    case "mapping":
      return [
        "| In the ZIP | In your project |",
        "| --- | --- |",
        ...result.files.map((file) => `| \`${file.archivePath}\` | \`${file.destinationPath}\` |`),
      ];
    case "files":
      return ["The full contents of every file are in the ZIP."];
  }
}
