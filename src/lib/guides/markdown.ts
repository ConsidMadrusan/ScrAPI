import { zipPath, type ChainedGuide, type GuideSection } from "./chained";
import { renderTree } from "./tree";
import type { GuideBlock } from "./types";

/** Name of the Markdown guide at the root of the ZIP. */
export const GUIDE_FILE_NAME = "INTEGRATION.md";

/**
 * Renders the chained guide as Markdown for INTEGRATION.md in the ZIP. It
 * contains the same steps as the guide on the page; file contents are in the
 * ZIP itself. Steps are numbered across all sections, as on the page.
 */
export function renderGuideMarkdown(guide: ChainedGuide): string {
  const lines = [`# ${guide.title}`, "", "Generated by ScrAPI.", ""];

  lines.push("The ZIP contains one folder per framework combination:", "");
  for (const section of guide.sections) lines.push(`- \`${section.key}/\`: ${section.label}`);
  lines.push("");

  if (guide.placeholders.length > 0) {
    lines.push("Values you must supply:", "");
    for (const placeholder of guide.placeholders) {
      lines.push(`- \`${placeholder.token}\`: ${placeholder.description}`);
    }
    lines.push("");
  }

  let number = 0;
  for (const section of guide.sections) {
    lines.push(`## ${section.label}`, "", section.guide.title, "");
    for (const step of section.guide.steps) {
      number += 1;
      lines.push(`### Step ${String(number)}: ${step.title}`, "");
      for (const block of step.blocks) lines.push(...renderBlock(block, section), "");
    }
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

function renderBlock(block: GuideBlock, section: GuideSection): string[] {
  const { result } = section;
  switch (block.kind) {
    case "text":
      return [block.text];
    case "list":
      return block.items.map((item) => `- ${item}`);
    case "command":
      return ["```sh", block.command, "```"];
    case "code":
      return [
        `${block.action === "create" ? "New file" : "Edit"} \`${block.file}\`:`,
        "",
        `\`\`\`${block.language}`,
        block.code.trimEnd(),
        "```",
      ];
    case "tree":
      return [
        "```text",
        renderTree(result.destinationRoot, result.files.map((file) => file.destinationPath)),
        "```",
      ];
    case "mapping":
      return [
        "| In the ZIP | In your project |",
        "| --- | --- |",
        ...result.files.map((file) => `| \`${zipPath(section, file.archivePath)}\` | \`${file.destinationPath}\` |`),
      ];
    case "files":
      return ["The full contents of every file are in the ZIP."];
  }
}
